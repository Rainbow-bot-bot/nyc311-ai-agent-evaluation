    "706.9 万条带地址记录归并为 573.1 万个事件簇，冗余 133.8 万条，"
    "占带地址记录的 18.9%、占分析口径全量 7,339,707 条的 18.2%。"
    "直接含义：任何用记录数衡量「某类问题有多严重」的比较，都掺入了约六分之一的重复上报量；"
    "而重复率在类型之间并不均匀（见下表，从 17.2% 到 39.4%），"
