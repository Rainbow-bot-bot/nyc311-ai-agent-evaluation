r = note(ws, r,
    "只有 28.0%（899,453 条）的结案说明表明发生了实质处置——「采取行动处置」「开具传票」「认定违规」"
    "或「已立案」；65.8%（2,118,277 条）属于「到场未发现问题 / 无需警方行动 / 到场时当事人已离开」；"
    "另有 2.8% 无法进入现场、1.2% 不属本机构管辖、0.6% 转交其他机构。"
    "这解释了为什么 NYPD 能在 99.2% 的情况下 24 小时内结案：多数派警以「到场核实后无需处置」收尾。"
    "结论层级：分类占比是可回查的事实；「结案速度快主要来自这种收尾方式」是与数据一致的推断；"
    "本数据无法判断这些「未发现问题」中有多少是问题已自行消失、有多少是出勤未能核实到，这一点仍未解决。")

r = section(ws, r, "  8.2 NYPD 主要问题类型的处置率对比（前 8 类）")
