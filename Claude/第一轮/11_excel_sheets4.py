# 12 上报渠道
# =========================================================
ws = wb.add_worksheet("12 上报渠道")
ws.hide_gridlines(2)
r = warn(ws, 0,
    "口径：渠道份额只在 ONLINE / MOBILE / PHONE 三类之间计算，整体排除约 7.9% 的 UNKNOWN 记录。"
    "原因见 12.2：UNKNOWN 不是随机缺失，而是特定机构特定类型的整类缺失，"
    "把它当成一个渠道会让份额随这些业务线的量起伏而失真。")

r = section(ws, r, "  12.1 渠道份额按月（已排除 UNKNOWN）")
d = T["t25_channel_monthly"]
r = write_table(ws, d, r, widths=[12, 16, 16, 18, 16], date_cols=("月份",))
nm = len(d)
ch = wb.add_chart({"type": "line"})
for j, (nmz, color) in enumerate([("网页 ONLINE%", "#2E75B6"), ("移动端 MOBILE%", "#548235"),
                                  ("电话 PHONE%", "#C00000")], start=2):
    ch.add_series({
        "name": nmz,
        "categories": ["12 上报渠道", r - nm - 2, 0, r - 3, 0],
        "values":     ["12 上报渠道", r - nm - 2, j, r - 3, j],
        "line": {"color": color, "width": 2.25},
    })
ch.set_title({"name": "上报渠道份额变化（%，已排除 UNKNOWN）"})
ch.set_y_axis({"name": "份额 %", "min": 0, "max": 60})
ch.set_x_axis({"name": "创建月份", "num_format": "yyyy-mm"})
ch.set_size({"width": 900, "height": 320})
ws.insert_chart(r, 0, ch)
r += 18
r = note(ws, r,
    "网页份额从 2024-09 的 44.6% 升到 2026-08 的 55.7%（+11.1 个百分点），"
    "电话从 32.1% 降到 23.8%（−8.3 个百分点），移动端在 19.0% ~ 24.1% 之间波动、无明显趋势。"
    "变化最集中的一段发生在 2025-11 到 2026-01：网页从 46.7% 两个月内跳到 56.6%，电话从 31.1% 降到 23.3%。"
    "本数据不含产品发布、客服排班或分类规则的记录，因此只能确认「份额在该时段发生了台阶式位移」这一事实，"
    "无法判断是入口改版、电话线路容量变化还是渠道归类调整所致——这属于未解决的问题。")

r = section(ws, r, "  12.2 为什么必须排除 UNKNOWN")
r = write_table(ws, T["t26_channel_unknown"], r, widths=[34, 10, 14, 18])
r = note(ws, r,
    "DOT 的交通信号、街灯，DOB 的建筑施工/用途/电梯等类型 100% 为 UNKNOWN，"
    "DSNY 涂鸦 95.1%、DOT 路面状况 63.6%。这些业务线大概率通过内部系统或巡检录入而非市民自助渠道进入，"
    "渠道字段从未被填写。由于这些类型的记录量本身在变化（如路面状况 2026-03 激增至 28,690 条），"
    "若把 UNKNOWN 当作一个渠道，其份额会随之波动（2026-03 一度达 13.8%），"
    "从而把其他渠道的份额一起带偏。排除后份额趋势才稳定可读。")

